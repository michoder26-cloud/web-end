const languages: Record<OfficeLanguage, OfficeWords> = { en, th }

/** The back office follows the site's language unless the owner chose one: Thai for a Thai site, English otherwise. */
export const officeLanguage = (settings: Pick<Settings, 'language' | 'officeLanguage'>): OfficeLanguage => {
  const chosen = settings.officeLanguage
  if (chosen && (officeLanguages as readonly string[]).includes(chosen)) return chosen as OfficeLanguage
  return settings.language?.toLowerCase().startsWith('th') ? 'th' : 'en'
}

export const officeWords = (language: OfficeLanguage = 'en') => languages[language] ?? en

export const officeText = (site: SiteRow) => officeWords(officeLanguage(JSON.parse(site.settings) as Settings))

/** For pages shown before the site has an owner: the browser's first choice between Thai and English. */
export const browserWords = (request: Request) => officeWords(/^\s*th\b/i.test(request.headers.get('accept-language') ?? '') ? 'th' : 'en')
